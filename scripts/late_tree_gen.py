#!/usr/bin/env python3
"""Generate ErdosResearch/SubsetSumLateTree.lean (session 84).

Reads the theorem names of the generated per-case modules below the late prefix
(SubsetSumPairGen, SubsetSumQuadGenA/B) and emits ONE combined theorem:
for all primes 23 < p < q < r not dividing n = 3^3*23*13^10*17^2*11 and all f, e >= 1,
n*p^f*q^e*r is not weird.  Dispatch is by `windowOK` (cheap Boolean: every odd number in the
range is a proven composite or one of the listed primes) and the existing theorems; nothing is re-checked.

Usage: python3 -I scripts/late_tree_gen.py > ErdosResearch/SubsetSumLateTree.lean
       STAR=1 python3 -I scripts/late_tree_gen.py > ErdosResearch/SubsetSumLateTreeStar.lean   (session 86: every last
       prime POWER r^k, from the star leaves of scripts/late_star_gen.py, the star q-tails and not_weird_ptail_star)
"""
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
STAR = os.environ.get("STAR") == "1"
PTAIL = 101 if STAR else 100          # p >= PTAIL: not_weird_ptail (star: not_weird_ptail_star)
SMALL = [3, 5, 7, 11, 13, 17, 19, 23]   # every odd composite < 29^2 = 841 has a factor here
N = 3**3 * 23 * 13**10 * 17**2 * 11
S = 256030928920159929


def read(name):
    with open(os.path.join(ROOT, "ErdosResearch", name + ".lean")) as fh:
        return fh.read()


def isprime(x):
    return x > 1 and all(x % d for d in range(2, int(x**0.5) + 1))


def main():
    pg = read("SubsetSumPairGen")
    pgs = read("SubsetSumPairGenStar") if STAR else pg
    PG = "SubsetSumPairGenStar" if STAR else "SubsetSumPairGen"
    quads = ("SubsetSumQuadGenAStar", "SubsetSumQuadGenBStar") if STAR else ("SubsetSumQuadGenA", "SubsetSumQuadGenB")
    ab = set(int(m) for m in re.findall(r"theorem not_weird_late_ab_(\d+) ", pg))
    qtail = {int(p): int(Q) for p, Q in re.findall(
        r"theorem not_weird_late_qtail_(\d+) .*?\(hQq : (\d+) ≤ q\)", pgs, re.S)}
    rng = {int(p): (int(a), int(b)) for p, a, b in re.findall(
        r"theorem not_weird_late_range_(\d+) .*?\(hq₀ : (\d+) ≤ q\) \(hq₁ : q ≤ (\d+)\)", pg, re.S)}
    leaves = {}
    for p, q in re.findall(r"theorem not_weird_late_pair_(\d+)_(\d+) ", pgs):
        leaves.setdefault(int(p), {})[int(q)] = "%s.not_weird_late_pair_%s_%s" % (PG, p, q)
    for mod in quads + ((PG,) if STAR else ()):
        for p, q in re.findall(r"theorem not_weird_(\d+)_(\d+) ", read(mod)):
            assert int(q) not in leaves.get(int(p), {}), (p, q)
            leaves.setdefault(int(p), {})[int(q)] = "%s.not_weird_%s_%s" % (mod, p, q)

    # ptail inequality (checked again by norm_num in Lean)
    if STAR:
        assert (S + N) * PTAIL ** 3 <= 2 * N * (PTAIL - 1) ** 3
    else:
        assert (S + N) * PTAIL * (PTAIL + 1) <= 2 * N * (PTAIL - 1) ** 2
    K = " ^ k" if STAR else ""
    HK = " hk" if STAR else ""
    NS = "SubsetSumLateTreeStar" if STAR else "SubsetSumLateTree"
    ps = [p for p in range(29, PTAIL) if isprime(p)]
    out = []
    w = out.append
    if STAR:
        w("module\n\npublic import ErdosResearch.SubsetSumWindow\npublic import ErdosResearch.SubsetSumPairGen\n"
          "public import ErdosResearch.SubsetSumPairGenStar\npublic import ErdosResearch.SubsetSumQuadGenAStar\n"
          "public import ErdosResearch.SubsetSumQuadGenBStar\npublic import ErdosResearch.SubsetSumTailStar\n\n"
          "@[expose] public section\n\n")
        w("/-!\n# Generated: the whole 3-prime sub-tree below the late prefix, every last prime power, as ONE theorem\n\n"
          "GENERATED by `STAR=1 python3 -I scripts/late_tree_gen.py` (do not edit by hand). With\n"
          "`n = lateN = 3^3·23·13^10·17^2·11`: for all primes `23 < p < q < r` not dividing `n` and all `f, e, k ≥ 1`,\n"
          "`n·p^f·q^e·r^k` is not weird (`not_weird_late_subtree_star`). The proof only dispatches to the star leaves of\n"
          "`SubsetSumPairGenStar` and `SubsetSumQuadGenAStar/B` (session 86, `scripts/late_star_gen.py`), the abundant and\n"
          "range theorems of `SubsetSumPairGen` (any cofactor), the star `q`-tails, `windowOK`, and\n"
          "`not_weird_ptail_star` for `p ≥ %d`.\n\n"
          "Reference: <https://www.erdosproblems.com/470>. See `notes/erdos-470.md` (session 86). Elementary; not a new\n"
          "result on #470.\n-/\n\n" % PTAIL)
    else:
        w("module\n\npublic import ErdosResearch.SubsetSumWindow\npublic import ErdosResearch.SubsetSumPairGen\n"
          "public import ErdosResearch.SubsetSumQuadGenA\npublic import ErdosResearch.SubsetSumQuadGenB\n"
          "public import ErdosResearch.SubsetSumBlock\n\n@[expose] public section\n\n")
        w("/-!\n# Generated: the whole 3-prime sub-tree below the late prefix, as ONE theorem\n\n"
          "GENERATED by `python3 -I scripts/late_tree_gen.py` (do not edit by hand). With `n = lateN = 3^3·23·13^10·17^2·11`:\n"
          "for all primes `23 < p < q < r` not dividing `n` and all `f, e ≥ 1`, `n·p^f·q^e·r` is not weird\n"
          "(`not_weird_late_subtree`). The proof only dispatches to the per-case theorems of `SubsetSumPairGen`\n"
          "(abundant `n p`, `q`-ranges, `q`-tails, `pairOK`) and `SubsetSumQuadGenA/B` (bounded pairs), with `windowOK`\n"
          "to show that every prime in each window has a theorem, plus `not_weird_ptail` for `p ≥ %d`.\n"
          "The last prime `r` appears to the first power only (stars `r^h`, `h ≥ 2`, are not covered).\n\n"
          "Reference: <https://www.erdosproblems.com/470>. See `notes/erdos-470.md` (session 84). Elementary; not a new\n"
          "result on #470.\n-/\n\n" % PTAIL)
    w("namespace ErdosResearch.%s\n\n" % NS)
    w("open ErdosResearch.SubsetSumWindow ErdosResearch.SubsetSumQuad\n\n")
    small = "[" + ", ".join(map(str, SMALL)) + "]"
    hyps = ("{f q e r : ℕ} (hq : q.Prime) (hr : r.Prime) (hpq : %d < q) (hqr : q < r)\n"
            "    (hqn : ¬ q ∣ lateN) (hrn : ¬ r ∣ lateN) (hf : 1 ≤ f) (he : 1 ≤ e) :\n"
            "    ¬ (lateN * %d ^ f * q ^ e * r" + K + ").Weird := by\n")
    if STAR:
        hyps = hyps.replace("{f q e r : ℕ}", "{f q e r k : ℕ}").replace("(he : 1 ≤ e) :", "(he : 1 ≤ e)\n    (hk : 1 ≤ k) :")
    for p in ps:
        if p in ab:
            w("set_option linter.unusedVariables false in\n")
        w("/-- Every `q > %d` below the prefix `lateN · %d^f`. -/\n" % (p, p))
        w("theorem late_p_%d " % p + hyps % (p, p))
        w("  have hp : (%d : ℕ).Prime := by norm_num\n" % p)
        if p in ab:
            assert p not in qtail and p not in rng and p not in leaves
            w("  rw [mul_assoc (lateN * %d ^ f)]\n" % p)
            w("  exact SubsetSumPairGen.not_weird_late_ab_%d hf (Nat.mul_pos (pow_pos hq.pos e) %s)\n\n"
              % (p, "(pow_pos hr.pos k)" if STAR else "hr.pos"))
            continue
        Q = qtail[p]
        w("  have hqp : ¬ q ∣ lateN * %d ^ f := not_dvd_mul_pow f hq hqn hp (by omega)\n" % p)
        w("  have hrM : ¬ r ∣ lateN * %d ^ f * q ^ e :=\n"
          "    not_dvd_mul_pow e hr (not_dvd_mul_pow f hr hrn hp (by omega)) hq (by omega)\n" % p)
        lo = p + 1
        if p in rng:
            a, b = rng[p]
            assert a == p + 1
            w("  rcases Nat.lt_or_ge q %d with h1 | h1\n" % (b + 1))
            w("  · exact SubsetSumPairGen.not_weird_late_range_%d hq (not_dvd_mul hq hqn hp (by omega)) (by omega)\n"
              "      (by omega) hf he %s\n" % (p, "(pow_pos hr.pos k)" if STAR else "hr.pos"))
            lo = b + 1
        w("  rcases Nat.lt_or_ge q %d with h2 | h2\n" % Q)
        L = sorted(leaves.get(p, {}))
        # sanity in Python: every prime in [lo, Q) has a leaf
        miss = [x for x in range(lo, Q) if isprime(x) and x not in L]
        assert not miss, (p, miss)
        assert all(lo <= x < Q for x in L), (p, lo, Q)
        if L:
            w("  · have hm := mem_of_windowOK (lo := %d) (P := %s) (L := [%s]) hq (by omega) (by omega) h2\n"
              "      (by decide +kernel)\n" % (lo, small, ", ".join(map(str, L))))
            w("    simp only [List.mem_cons, List.not_mem_nil, or_false] at hm\n")
            w("    rcases hm with " + " | ".join(["rfl"] * len(L)) + "\n")
            for x in L:
                w("    · exact %s hf he hr hrM%s\n" % (leaves[p][x], HK))
        else:
            w("  · exact absurd (mem_of_windowOK (lo := %d) (P := %s) (L := []) hq (by omega) (by omega) h2\n"
              "      (by decide +kernel)) (List.not_mem_nil)\n" % (lo, small))
        w("  · exact %s.not_weird_late_qtail_%d hq hqp hr hrM h2 (by omega)\n\n" % (PG, p))
    if STAR:
        w("/-- **The whole 3-prime sub-tree below the late prefix, every last prime power.** -/\n")
        w("theorem not_weird_late_subtree_star {p q r f e k : ℕ} (hp : p.Prime) (hq : q.Prime) (hr : r.Prime)\n"
          "    (h23 : 23 < p) (hpq : p < q) (hqr : q < r) (hpn : ¬ p ∣ lateN) (hqn : ¬ q ∣ lateN)\n"
          "    (hrn : ¬ r ∣ lateN) (hf : 1 ≤ f) (he : 1 ≤ e) (hk : 1 ≤ k) :\n"
          "    ¬ (lateN * p ^ f * q ^ e * r ^ k).Weird := by\n")
    else:
        w("/-- **The whole 3-prime sub-tree below the late prefix** (last prime to the first power). -/\n")
        w("theorem not_weird_late_subtree {p q r f e : ℕ} (hp : p.Prime) (hq : q.Prime) (hr : r.Prime)\n"
          "    (h23 : 23 < p) (hpq : p < q) (hqr : q < r) (hpn : ¬ p ∣ lateN) (hqn : ¬ q ∣ lateN)\n"
          "    (hrn : ¬ r ∣ lateN) (hf : 1 ≤ f) (he : 1 ≤ e) : ¬ (lateN * p ^ f * q ^ e * r).Weird := by\n")
    w("  rcases Nat.lt_or_ge p %d with h | h\n" % PTAIL)
    w("  · have hm := mem_of_windowOK (P := %s) (L := [%s]) hp (by omega) (Nat.succ_le_of_lt h23) h\n"
      "      (by decide +kernel)\n" % (small, ", ".join(map(str, ps))))
    w("    simp only [List.mem_cons, List.not_mem_nil, or_false] at hm\n")
    w("    rcases hm with " + " | ".join(["rfl"] * len(ps)) + "\n")
    for p in ps:
        w("    · exact late_p_%d hq hr hpq hqr hqn hrn hf he%s\n" % (p, HK))
    if STAR:
        w("  · have hqp : ¬ q ∣ lateN * p ^ f := not_dvd_mul_pow f hq hqn hp (by omega)\n"
          "    have hrM : ¬ r ∣ lateN * p ^ f * q ^ e :=\n"
          "      not_dvd_mul_pow e hr (not_dvd_mul_pow f hr hrn hp (by omega)) hq (by omega)\n"
          "    exact ErdosResearch.SubsetSumTailStar.not_weird_ptail_star (Q := %d) (by norm_num)\n"
          "      ErdosResearch.SubsetSumFifthLoop.intervalGap_late_prefix.1 hp hpn hq hqp hr hrM (by norm_num) h\n"
          "      (by omega) (by omega) (by norm_num)\n\n" % PTAIL)
    else:
        w("  · exact ErdosResearch.SubsetSumBlock.not_weird_ptail (Q := %d) (by norm_num)\n"
          "      ErdosResearch.SubsetSumFifthLoop.intervalGap_late_prefix.1 hp hpn hq hqn hr hrn hpq (by omega)\n"
          "      (by omega) (by norm_num) h (by norm_num)\n\n" % PTAIL)
    w("end ErdosResearch.%s\n" % NS)
    sys.stdout.write("".join(out))


if __name__ == "__main__":
    main()
