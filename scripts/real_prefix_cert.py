# Session 60 (notes/erdos-470.md): Lean certificate "no N·q weird" (q prime, q ∤ N) for ONE given deficient 5-prime
# prefix N, with the session-58 machinery (multi_plan + build + emit from scripts/late_cert_gen.py).
# Usage: python3 scripts/real_prefix_cert.py '3^17*5^24*17^4*257^4*113149' > ErdosResearch/OddWeirdRealPrefix.lean
# The prefix used in the repo was read from the progress log of the omega = 6 workers (root 3^17), not computed here.
# Python only; it does NOT run the omega = 6 search.
import sys, os
spec = sys.argv[1]
f = {}
for t in spec.split('*'):
    p, _, e = t.partition('^')
    f[int(p)] = int(e or 1)
gen = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'late_cert_gen.py')
sys.argv = [gen, '100000', '1', '100000', '10000000']
g = {'__file__': gen, '__name__': 'gen'}
exec(open(gen).read().split("DRY = os.environ")[0], g)
pl = g['multi_plan'](f)
assert pl and pl[2], "no multi-raise plan for this prefix"
d = g['build'](f, pl)
assert d is not None, "plan outside the size limits"
h = g['HEADER'].replace("`scripts/late_cert_gen.py {args}`", f"`scripts/real_prefix_cert.py {spec}`")
h = h.replace('ErdosResearch.OddWeirdPlans', 'ErdosResearch.OddWeirdRealPrefix')
h = h.replace("prefix `N` drawn from the same random family as\n`MULTI=1 scripts/raise_late_plan.py`:", "prefix `N`:")
h = h.replace("These are random test prefixes, not the prefixes of the omega = 6 search.",
              "`N` is a real node of the omega = 6 search (read from the progress log of root 3^17); the instance\n"
              "certifies that node's last-prime family only, not the root.")
h = h.replace("set_option Elab.async false\n", "set_option Elab.async false\n-- `gapCertM` over a 4500-divisor cofactor and `lastOK` with B ≈ 1.4·10^5 need a deep kernel recursion.\nset_option maxRecDepth 1000000\n")
import re
h = re.sub(r"GENERATED by .*?\(`lastOK`\)\.\n", "GENERATED by `scripts/real_prefix_cert.py " + spec + "` (do not edit by hand).\n"
           "No `N · q` (`q` prime, `q ∤ N`) is weird, for one deficient 5-prime prefix `N`: bitset base,\n"
           "prime-power steps, raises with a greedy gap bound, all last primes at once (`lastOK`).\n", h, flags=re.S)
h = h.replace("-- `gapCertM` over a 4500-divisor cofactor and `lastOK` with B ≈ 1.4·10^5 need a deep kernel recursion.",
              "-- `gapCertM` on a 4500-divisor cofactor and `lastOK` (B ≈ 1.4·10^5) recurse deeply in the kernel.")
print(h + g['emit'](0, d) + "\nend ErdosResearch.OddWeirdRealPrefix")
