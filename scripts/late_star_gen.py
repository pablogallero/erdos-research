#!/usr/bin/env python3
"""Session 86 (notes/erdos-470.md): star versions of the late prefix's generated leaves.

Reads the generated modules of sessions 82-83 (SubsetSumPairGen, SubsetSumQuadGenA/B) and rewrites every leaf with the
star Booleans of session 85 (SubsetSumPairStar: pairOK -> pairStarOK, boundedOK -> boundedStarOK, same certificate
parameters, plus one fixed skip list L and fuel). The q-tails move to the star bound of `not_weird_qtail_star`
((S+n) p Q^2 <= 2 n (p-1) (Q-1)^2); the one prime that this adds to a window, (89, 107), gets a new boundedStarOK leaf
(parameters from quad_probe.pair). Nothing here is trusted: every Boolean is re-checked by `decide +kernel`.
Decides nothing about #470 by itself and runs no search (no owf).

Usage (from the repo root; byte-identical on rerun):
  python3 -I scripts/late_star_gen.py pair  > ErdosResearch/SubsetSumPairGenStar.lean
  python3 -I scripts/late_star_gen.py quadA > ErdosResearch/SubsetSumQuadGenAStar.lean
  python3 -I scripts/late_star_gen.py quadB > ErdosResearch/SubsetSumQuadGenBStar.lean
"""
import os
import re
import sys

sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
ROOT = os.path.join(HERE, "..")

N = 3 ** 3 * 23 * 13 ** 10 * 17 ** 2 * 11
S, C, G = 256030928920159929, 2295, 5
FUEL = 12


def isprime(x):
    return x > 1 and all(x % d for d in range(2, int(x ** 0.5) + 1))


LSKIP = [x for x in range(3, 260) if isprime(x)]   # every odd composite < 263^2 has a proper factor here
LTXT = "[" + ", ".join(map(str, LSKIP)) + "]"


def read(name):
    with open(os.path.join(ROOT, "ErdosResearch", name + ".lean")) as fh:
        return fh.read()


def star_qtail(p, Q0):
    """Least Q >= Q0 with (S+N) p Q^2 <= 2 N (p-1) (Q-1)^2."""
    A, B = 2 * N * (p - 1), (S + N) * p
    Q = Q0
    while B * Q * Q > A * (Q - 1) * (Q - 1):
        Q += 1
    return Q


def blocks(text):
    """Theorem blocks (with an optional preceding doc comment), separated by blank lines."""
    return [b for b in text.split("\n\n") if re.search(r"^theorem ", b, re.M)]


def star_leaf(b, kind):
    b = b.replace("{f e r : ℕ}", "{f e r k : ℕ}")
    b2 = re.sub(r"\* r\)\.Weird :=", "* r ^ k).Weird :=", b)
    assert b2 != b
    b = re.sub(r"\) :(\s+)¬ \(", r") (hk : 1 ≤ k) :\1¬ (", b2, count=1)
    old, new = ("not_weird_of_pairOK", "not_weird_of_pairStarOK") if kind == "pair" else \
        ("not_weird_of_boundedOK", "not_weird_of_boundedStarOK")
    assert old in b
    b = b.replace(old, new)
    b2 = b.replace("\n    (by norm_num) (by norm_num) ErdosResearch.SubsetSumFifthLoop.intervalGap_late_prefix",
                   " (L := LSKIP) (fuel := %d)\n    (by norm_num) (by norm_num) "
                   "ErdosResearch.SubsetSumFifthLoop.intervalGap_late_prefix" % FUEL, 1)
    assert b2 != b
    assert b2.rstrip().endswith("hf he hr hrM")
    b = b2.rstrip() + " hk"
    b = b.replace("boundedOK`)", "boundedStarOK`, every `r^k`)")
    return b


HEAD = """module

{imports}

@[expose] public section

/-!
# Generated: star versions of the leaves below the late prefix ({what})

GENERATED by `python3 -I scripts/late_star_gen.py {arg}` from `{src}` (do not edit by hand). Same certificate parameters,
star Booleans of session 85 (`SubsetSumPairStar`): each leaf now covers every last prime POWER `r^k` (`k ≥ 1`).
{extra}Reference: <https://www.erdosproblems.com/470>. See `notes/erdos-470.md` (session 86). Elementary; not a new result
on #470.
-/

set_option Elab.async false

namespace ErdosResearch.{ns}

open ErdosResearch.SubsetSumPairStar ErdosResearch.SubsetSumQuad

/-- Skip list for composite star candidates (`skipS`): the odd primes below 260. -/
abbrev LSKIP : List ℕ := {L}

"""


def main():
    arg = sys.argv[1]
    out = []
    if arg == "pair":
        pg = read("SubsetSumPairGen")
        extra = ("The `q`-tails use `not_weird_qtail_star`; the abundant (`ab`) and `range` theorems of `SubsetSumPairGen`\n"
                 "already allow any cofactor and are reused as they are. The bounded pair `(89, 107)` is new: the star\n"
                 "`q`-tail of `p = 89` is 108, one above the old one.\n")
        out.append(HEAD.format(imports="public import ErdosResearch.SubsetSumPairStar\n"
                               "public import ErdosResearch.SubsetSumTailStar\npublic import ErdosResearch.SubsetSumPairGen",
                               what="pairs and q-tails", arg=arg, src="SubsetSumPairGen", extra=extra,
                               ns="SubsetSumPairGenStar", L=LTXT))
        for b in blocks(pg):
            m = re.search(r"theorem not_weird_late_(\w+?)_(\d+)", b)
            kind = m.group(1)
            if kind == "pair":
                out.append(star_leaf(b, "pair") + "\n\n")
            elif kind == "qtail":
                p = int(m.group(2))
                Q0 = int(re.search(r"\(hQq : (\d+) ≤ q\)", b).group(1))
                Q = star_qtail(p, Q0)
                M = "3 ^ 3 * 23 * 13 ^ 10 * 17 ^ 2 * 11 * %d ^ f" % p
                out.append(
                    "theorem not_weird_late_qtail_%d {f q e r k : ℕ} (hq : q.Prime) (hqn : ¬ q ∣ %s)\n"
                    "    (hr : r.Prime) (hrn : ¬ r ∣ %s * q ^ e) (hQq : %d ≤ q) (hQr : %d ≤ r) :\n"
                    "    ¬ (%s * q ^ e * r ^ k).Weird :=\n"
                    "  ErdosResearch.SubsetSumTailStar.not_weird_qtail_star (S := %d) (by norm_num)\n"
                    "    ErdosResearch.SubsetSumFifthLoop.intervalGap_late_prefix.1 (by norm_num) (by norm_num) hq hqn hr hrn\n"
                    "    (by norm_num) hQq hQr (by norm_num)\n\n" % (p, M, M, Q, Q, M, S))
            else:
                assert kind in ("ab", "range"), kind
        # the new bounded pair (89, 107)
        import quad_probe
        res, why = quad_probe.pair(N, S, C, G, 89, 107)
        assert res is not None, why
        os.environ["LEAN"] = "late"
        os.environ["NS"] = "X"
        mod = quad_probe.emit([(89, 107, res)], 0, "")
        b = [x for x in blocks(mod)][0]
        out.append(star_leaf(b, "bounded") + "\n\n")
        out.append("end ErdosResearch.SubsetSumPairGenStar\n")
    else:
        src = {"quadA": "SubsetSumQuadGenA", "quadB": "SubsetSumQuadGenB"}[arg]
        ns = src + "Star"
        out.append(HEAD.format(imports="public import ErdosResearch.SubsetSumPairStar", what="bounded pairs", arg=arg,
                               src=src, extra="", ns=ns, L=LTXT))
        for b in blocks(read(src)):
            out.append(star_leaf(b, "bounded") + "\n\n")
        out.append("end ErdosResearch.%s\n" % ns)
    sys.stdout.write("".join(out))


if __name__ == "__main__":
    main()
