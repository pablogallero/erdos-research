#!/usr/bin/env python3
"""Erdős #470: cover odd numbers with k prime factors by "multiple of an odd PAN" or "deficient".

Usage: python3 scripts/odd_pan_search.py K [--lean OUT.lean]

Runs the same search as `chk` in ErdosResearch/OddWeirdFour.lean (node count only), collects the
abundant leaves, reduces each to a primitive abundant divisor ("bases"), and for each base finds
a set X of proper divisors with sum σ(b) - 2b (so that the other proper divisors sum to b, i.e. b
is pseudoperfect). With --lean it writes the data file (bases + certificates).
"""
import sys
from fractions import Fraction as F

sys.setrecursionlimit(100000)


def isprime(q):
    if q < 2:
        return False
    d = 2
    while d * d <= q:
        if q % d == 0:
            return False
        d += 1
    return True


def sig(p, e):
    return (p ** (e + 1) - 1) // (p - 1)


def fac(n):
    f = {}
    p = 3
    while n > 1:
        while n % p == 0:
            n //= p
            f[p] = f.get(p, 0) + 1
        p += 2
    return f


def ratio(f):
    r = F(1)
    for p, e in f.items():
        r *= F(sig(p, e), p ** e)
    return r


def bound(q, j):
    r = F(1)
    for i in range(j):
        r *= F(q + 2 * i, q + 2 * i - 1)
    return r


def search(N, U, j, q0, acc):
    """Mirror of `chk` with abundance of N as the leaf test. Returns True if the node closes."""
    acc["n"] += 1
    if ratio(fac(N)) >= 2:
        acc["L"].append(N)
        return True
    if j == 0:
        return U < 2
    q = q0
    while True:
        if U * bound(q, j) < 2:
            return True
        if isprime(q):
            e = 1
            while True:
                Nq = N * q ** e
                sub = {"n": 0, "L": []}
                if search(Nq, U * F(q, q - 1), j - 1, q + 2, sub):
                    acc["n"] += sub["n"]
                    acc["L"] += sub["L"]
                    break
                if not search(Nq, U * F(sig(q, e), q ** e), j - 1, q + 2, acc):
                    return False
                e += 1
        q += 2


def primitive(f):
    f = dict(f)
    changed = True
    while changed:
        changed = False
        for p in sorted(f):
            g = dict(f)
            g[p] -= 1
            if g[p] == 0:
                del g[p]
            if ratio(g) >= 2:
                f, changed = g, True
                break
    return f


def divisors(f):
    ds = [1]
    for p, e in f.items():
        ds = [d * p ** i for d in ds for i in range(e + 1)]
    return sorted(ds)


def small_subset(ds, D, lim=10 ** 6):
    ds = sorted([d for d in ds if d <= D], reverse=True)
    pre = [0] * (len(ds) + 1)
    for i in range(len(ds) - 1, -1, -1):
        pre[i] = pre[i + 1] + ds[i]
    best, cnt = [None], [0]

    def dfs(i, r, sol):
        cnt[0] += 1
        if cnt[0] > lim:
            return
        if r == 0:
            if best[0] is None or len(sol) < len(best[0]):
                best[0] = list(sol)
            return
        if best[0] is not None and len(sol) + 1 >= len(best[0]):
            return
        if i == len(ds) or pre[i] < r:
            return
        if ds[i] <= r:
            sol.append(ds[i])
            dfs(i + 1, r - ds[i], sol)
            sol.pop()
        dfs(i + 1, r, sol)

    dfs(0, D, [])
    return best[0]


def main():
    k = int(sys.argv[1])
    acc = {"n": 0, "L": []}
    ok = search(1, F(1), k, 3, acc)
    leaves = sorted(set(acc["L"]))
    print(f"closed={ok} nodes={acc['n']} leaves={len(leaves)}")
    bases = set()
    for N in leaves:
        g = primitive(fac(N))
        b = 1
        for p, e in g.items():
            b *= p ** e
        bases.add(b)
    bases = sorted(bases)
    certs = []
    for b in bases:
        f = fac(b)
        s = 1
        for p, e in f.items():
            s *= sig(p, e)
        x = small_subset([d for d in divisors(f) if d < b], s - 2 * b)
        assert x is not None, b
        certs.append((b, sorted(f.items()), sorted(x, reverse=True)))
    print(f"bases={len(bases)} certificate_numbers={sum(len(c[2]) for c in certs)}")
    if "--lean" in sys.argv:
        out = sys.argv[sys.argv.index("--lean") + 1]
        with open(out, "w") as fh:
            fh.write("import Mathlib\n\n/-!\nData for `OddWeirdFour.lean`, generated by "
                     f"`scripts/odd_pan_search.py {k} --lean`.\n\n"
                     f"`panBases`: the {len(bases)} odd primitive abundant numbers with at most {k} "
                     "prime factors\nthat the search reaches. `panCerts`: for each, its factorization "
                     "and a strictly decreasing\nlist of proper divisors with sum `σ(b) - 2b`.\n-/\n\n"
                     "namespace Erdos470Research\n\n")
            fh.write("set_option maxRecDepth 100000\n\n/-- Odd primitive abundant numbers used as leaves of the search. -/\n")
            fh.write("def panBases : List ℕ := [\n  " +
                     ",\n  ".join(", ".join(str(b) for b in bases[i:i + 6])
                                 for i in range(0, len(bases), 6)) + "]\n\n")
            fh.write("/-- `(b, factorization of b, divisors left out)`. -/\n")
            fh.write("def panCerts : List (ℕ × List (ℕ × ℕ) × List ℕ) := [\n")
            fh.write(",\n".join("  (%d, [%s], [%s])" % (b, ", ".join(f"({p}, {e})" for p, e in f),
                                                         ", ".join(map(str, x)))
                                for b, f, x in certs))
            fh.write("]\n\nend Erdos470Research\n")


if __name__ == "__main__":
    main()
